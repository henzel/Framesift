def tr(text: str, **params: object) -> str:
    """Translate a GUI string. Keys are the English texts themselves."""
    lang = current_language()
    out = RU.get(text, text) if lang == "ru" else text
    if params:
        try:
            return out.format(**params)
        except (KeyError, IndexError, ValueError):
            return out
    return out
